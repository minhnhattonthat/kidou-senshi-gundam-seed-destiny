"""Generate tbl/jp.tbl from the font order (archive 6.9-6.11 main font, 6.12 kanji bank, 6.13 symbol bank).
Font order confirmed from rendered glyph sheets (docs/re/text.md)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LATIN = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
HIRA = ('あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん'
        'ゃゅょっがぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽぁぃぅぇぉ')
KATA = ('アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン'
        'ャュョッガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポァィゥェォヴ')
# one list item per glyph; the bank holds duplicate kanji, suffixed ₂/₃ so the table stays one-to-one (roundtrip)
KANJI = (['()'] + list('決連続技次着地落時間空中後回交換様々物事等色場所手入何来取沈誰死勝負殺言日今戦守以上人動緒隊長'
                       '報告失態腕前信道瞬撃抹必変赤本気私楽整備渡最強悲家族機国') + ['回₂'] +
         list('離脱合体野郎土産末見極帰還類権利憎争育開閉定存在業休生成績大') + ['続₂'] + list('不可能世界亡力') +
         ['気₂', '合₂'] + list('一行滅当男接') + ['続₃'] + list('敗戻押期待結果知礼父母敵昔通屋衣装新選択買天'))
# symbol bank 6.13 (EC xx); 0F-10, 1B+ unidentified so far -> stay [EC][xx]
SYM = {0x00: '0', 0x01: '1', 0x02: '2', 0x03: '3', 0x04: '4', 0x05: '5', 0x06: '6', 0x07: '7', 0x08: '8',
       0x09: '9', 0x0A: '．', 0x0B: '！', 0x0C: '？', 0x0D: '・', 0x0E: '…', 0x0F: '－', 0x11: '｡', 0x12: '：',
       0x13: '〈', 0x14: '〉', 0x15: '。', 0x16: '、', 0x17: 'ー', 0x18: '～', 0x19: '「', 0x1A: '」'}


def lines():
    out = ['# generated by tools/mktbl.py', '00=＿', '01=▼']
    out += ['%02X=%s' % (0x02 + i, c) for i, c in enumerate(LATIN)]
    out += ['%02X=%s' % (0x36 + i, c) for i, c in enumerate(HIRA)]
    out += ['%02X=%s' % (0x86 + i, c) for i, c in enumerate(KATA)]
    out += ['ED%02X=%s' % (i, c) for i, c in enumerate(KANJI)]
    assert len(set(KANJI)) == len(KANJI)
    out += ['EC%02X=%s' % (k, v) for k, v in sorted(SYM.items())]
    # control codes: parser 0x08031FF8, jump table 0x08032054 (EE-FF); arg counts from handlers + corpus stats
    out += ['ECFF={num}', 'E0={sp6}', 'E1={sp8}', 'EE={ee:1}', 'EF={ef:1}', 'F0={f0}', 'F1={f1}', 'F2={f2}',
            'F3={f3}', 'F4={f4:1}', 'F5={f5:3}', 'F6={f6:3}', 'F7={f7:1}', 'F8={f8:1}', 'F9={f9:3}', 'FA={wait:1}',
            'FB={fb:1}', 'FC={page}', 'FD={key}', 'FE={n}', 'FF={end}']
    return out


if __name__ == '__main__':
    assert len(HIRA) == 0x86 - 0x36 and len(KATA) == 0xD7 - 0x86 and len(KANJI) == 146, (len(HIRA), len(KATA), len(KANJI))
    (ROOT / 'tbl').mkdir(exist_ok=True)
    (ROOT / 'tbl/jp.tbl').write_text('\n'.join(lines()) + '\n', encoding='utf-8', newline='\n')
